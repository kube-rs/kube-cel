/// Whether a code point of `lo..=hi` has a case in Go's tables or the `regex`
/// crate's.
pub(crate) fn cased(lo: u32, hi: u32) -> bool {
    let (ranges, _) = CASED.as_chunks::<2>();
    // The first range that ends at or after `lo`.
    let i = ranges.partition_point(|&[_, end]| end < lo);
    i < ranges.len() && ranges[i][0] <= hi
}

/// Whether the `regex` crate's tables are the Unicode 16.0.0 ones [`DIFFERS`]
/// was computed against: U+1C89 (assigned in 16.0) is assigned there, and
/// U+20C1 (assigned in 17.0) is not. Checked once.
pub(crate) fn known_tables() -> bool {
    static KNOWN: std::sync::LazyLock<bool> = std::sync::LazyLock::new(|| {
        regex::Regex::new(r"\p{Cn}")
            .is_ok_and(|unassigned| !unassigned.is_match("\u{1C89}") && unassigned.is_match("\u{20C1}"))
    });
    *KNOWN
}

/// Whether Go's `regexp` and the `regex` crate may read `c` otherwise in a
/// Unicode class or under case folding.
pub(crate) fn differs(c: char) -> bool {
    let c = u32::from(c);
    let (ranges, _) = DIFFERS.as_chunks::<2>();
    let after = ranges.partition_point(|&[start, _]| start <= c);
    after > 0 && c <= ranges[after - 1][1]
}

#[cfg(test)]
mod tests {
    #[test]
    fn ranges_are_in_order() {
        for table in [super::DIFFERS, super::CASED] {
            let (ranges, rest) = table.as_chunks::<2>();
            assert!(rest.is_empty());
            assert!(ranges.iter().all(|[start, end]| start <= end));
            assert!(ranges.windows(2).all(|w| w[0][1] + 1 < w[1][0]));
        }
    }

    #[test]
    fn cased_holds_where_a_character_folds_to_another() {
        use super::cased;
        // `k` with `K` and the Kelvin sign, `ΐ` with U+1FD3 in the `regex`
        // crate only, `ɤ` with U+A7CB (new in Unicode 16.0).
        for c in ['k', 'K', '\u{212A}', 'ΐ', '\u{1FD3}', 'ɤ', '\u{A7CB}'] {
            assert!(cased(u32::from(c), u32::from(c)), "{c:?}");
        }
        for c in ['1', '_', ' ', '日', '\u{378}'] {
            assert!(!cased(u32::from(c), u32::from(c)), "{c:?}");
        }
        assert!(!cased(0x30, 0x39) && cased(0x30, 0x41) && cased(0x0, 0x10FFFF));
    }

    /// `DIFFERS` is computed against the `regex` crate's Unicode 16.0.0
    /// tables: when this fails, the crate has other ones, every match that
    /// reads tables fails, and `DIFFERS` is to be computed again.
    #[test]
    fn the_regex_crate_has_unicode_16_tables() {
        assert!(super::known_tables());
    }

    #[test]
    fn differs_where_go_reads_otherwise() {
        // Assigned since Unicode 15.0 (a letter since 16.0), never assigned, a
        // fold Go lacks (U+0390 and U+1FD3), a partner new in 16.0 (U+0264
        // and U+A7CB).
        for c in [
            '\u{1C89}',
            '\u{378}',
            '\u{390}',
            '\u{1FD3}',
            '\u{264}',
            '\u{A7CB}',
            '\u{10FFFF}',
        ] {
            assert!(super::differs(c), "{c:?}");
        }
        for c in ['a', 'é', 'Ω', 'ι', '日', '\u{1F600}', '\u{E000}'] {
            assert!(!super::differs(c), "{c:?}");
        }
    }
}
