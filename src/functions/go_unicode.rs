//! Where Go's Unicode tables and the `regex` crate's may read a character
//! otherwise.
//!
//! The apiserver's `regexp` (go1.26.2) reads Unicode classes and case folding
//! with Go's Unicode 15.0.0 tables; the `regex` crate (`regex-syntax` 0.8)
//! with Unicode 16.0.0's, and folds a few characters Go does not. A
//! translated pattern that reads those tables (a Unicode class, or case
//! folding of a character that has a case) can therefore match a character
//! otherwise than Go, and only such a character: [`DIFFERS`] holds every code point where the two may disagree,
//! computed by comparing, for every code point,
//!
//! - its membership of each Unicode class kube-cel translates (`re2`), plain
//!   and case-folded: Go's `regexp/syntax` ranges against the `regex` crate's
//!   match of the translation;
//! - its case-folding orbit: Go's `unicode.SimpleFold` cycle against
//!   `regex-syntax`'s simple case folding;
//!
//! together with every code point Go's tables do not assign (Unicode 15.0.0's
//! unassigned ones, whatever a later Unicode makes of them).
//!
//! Case folding reads the tables only for a character that has a case: one
//! whose orbit holds another character, in Go's `unicode.SimpleFold` or in
//! `regex-syntax`'s simple case folding ([`CASED`]). A folded literal or class
//! of none of them (`(?i)1`, `(?i)[0-9]`) matches the same characters in both.
//!
//! It holds for the crate's Unicode 16.0.0 tables only: `Cargo.toml` takes
//! any `regex` 1.x, which may come with other ones. [`known_tables`] tells,
//! and where it does not hold, a match that reads tables fails whatever the
//! string, until [`DIFFERS`] is computed again for the new tables.

