//! Go's `strconv.IsPrint`, which decides what `%q` (`strconv.Quote`) prints as
//! is and what it escapes, and `strconv.Quote` itself. The tables are those of go1.26.2's
//! `src/strconv/isprint.go` (Unicode 15.0.0), the reference apiserver's
//! toolchain; newer Go releases print code points assigned in later
//! Unicode versions. Copied from the Go source (Copyright The Go Authors,
//! BSD-style license); regenerate them from that file, not by hand.

/// Go's `strconv.Quote` (and `%q` of a string) on Go string bytes: double
/// quotes, `\"` and `\\`, what [`is_print`] accepts as is, the C escapes,
/// `\xNN` below space, for DEL and for each byte that is not part of valid
/// UTF-8, and `\uNNNN` / `\UNNNNNNNN` for the rest.
pub(crate) fn quote(s: &[u8]) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    let mut i = 0;
    while i < s.len() {
        // One character if the bytes at `i` start a valid one (as Go's
        // `utf8.DecodeRuneInString`), else that one byte.
        let chunk = &s[i..(i + 4).min(s.len())];
        let c = match std::str::from_utf8(chunk) {
            Ok(text) => text.chars().next(),
            Err(e) if e.valid_up_to() > 0 => std::str::from_utf8(&chunk[..e.valid_up_to()])
                .ok()
                .and_then(|text| text.chars().next()),
            Err(_) => None,
        };
        let Some(c) = c else {
            out.push_str(&format!("\\x{:02x}", s[i]));
            i += 1;
            continue;
        };
        i += c.len_utf8();
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            c if is_print(c) => out.push(c),
            '\u{07}' => out.push_str("\\a"),
            '\u{08}' => out.push_str("\\b"),
            '\u{0c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{0b}' => out.push_str("\\v"),
            c if c < ' ' || c == '\u{7f}' => out.push_str(&format!("\\x{:02x}", u32::from(c))),
            c if u32::from(c) < 0x10000 => out.push_str(&format!("\\u{:04x}", u32::from(c))),
            c => out.push_str(&format!("\\U{:08x}", u32::from(c))),
        }
    }
    out.push('"');
    out
}

/// Whether Go's `strconv.IsPrint` reports `c` as printable: letters, marks,
/// numbers, punctuation, symbols and the ASCII space, as of Unicode 15.0.0.
pub(crate) fn is_print(c: char) -> bool {
    let r = u32::from(c);
    // Latin-1: space through `~`, and `¡` through `ÿ` but the soft hyphen.
    if r <= 0xFF {
        return (0x20..=0x7E).contains(&r) || ((0xA1..=0xFF).contains(&r) && r != 0xAD);
    }
    // The first entry at or after `r` is the start (even index) or the end (odd
    // index) of a printable range that may hold it; then `r` must not be listed
    // as an exception.
    if let Ok(rr) = u16::try_from(r) {
        let i = IS_PRINT16.partition_point(|&x| x < rr);
        if i >= IS_PRINT16.len() || rr < IS_PRINT16[i & !1] || IS_PRINT16[i | 1] < rr {
            return false;
        }
        return IS_NOT_PRINT16.binary_search(&rr).is_err();
    }
    let i = IS_PRINT32.partition_point(|&x| x < r);
    if i >= IS_PRINT32.len() || r < IS_PRINT32[i & !1] || IS_PRINT32[i | 1] < r {
        return false;
    }
    if r >= 0x20000 {
        return true;
    }
    let rr = u16::try_from(r - 0x10000).expect("below 0x20000");
    IS_NOT_PRINT32.binary_search(&rr).is_err()
}

